// Summary of an eval batch (3D-28): one row per run, one line per task, totals. Reads every run record
// in the results dir, so a batch may be run in several invocations.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** @param {string} dir @returns {any[]} */
export function readRecords(dir) {
  return readdirSync(dir)
    .filter((f) => /-run\d+\.json$/.test(f))
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
}

/** @param {number | null | undefined} n @param {number} d */
const f = (n, d = 2) => (typeof n === 'number' ? n.toFixed(d) : '-');
/** @param {number} n */
const k = (n) => `${Math.round(n / 1000)}k`;

/**
 * @param {string} label
 * @param {any[]} records
 * @param {{id: string, covers: string[]}[]} tasks
 * @returns {string}
 */
export function summarize(label, records, tasks) {
  const byTask = new Map(tasks.map((t) => [t.id, /** @type {any[]} */ ([])]));
  for (const r of records) byTask.get(r.task)?.push(r);
  const lines = [
    `# Agent evals - ${label}`,
    '',
    `Ref: ${[...new Set(records.map((r) => r.startSha?.slice(0, 7)))].join(', ') || '-'} (start state after setup).`,
    `Model: ${[...new Set(records.map((r) => r.model))].join(', ') || '-'}. Generated by tools/agent-evals/cli.mjs.`,
    '',
    '| Task | Covers | Scores | Holds | Cost USD | Context tokens (in+cache) | Output tokens | Turns | Failed checks |',
    '|---|---|---|---|---:|---:|---:|---:|---|',
  ];
  let cost = 0;
  let holding = 0;
  let measured = 0;
  for (const t of tasks) {
    const rs = (byTask.get(t.id) ?? []).sort((a, b) => a.run - b.run);
    if (rs.length === 0) continue;
    measured += 1;
    const holds = rs.every((r) => r.holds);
    if (holds) holding += 1;
    const c = rs.reduce((s, r) => s + (r.costUsd ?? 0), 0);
    cost += c;
    const ctx = rs.map((r) => k(r.usage.input + r.usage.cacheCreate + r.usage.cacheRead)).join(' / ');
    const out = rs.map((r) => k(r.usage.output)).join(' / ');
    const failed = [
      ...new Set(rs.flatMap((r) => r.checks.filter((/** @type {any} */ x) => !x.pass).map((/** @type {any} */ x) => `${x.id}(r${r.run})`))),
    ];
    lines.push(
      `| ${t.id} | ${t.covers.join(', ')} | ${rs.map((r) => f(r.score)).join(' / ')} | ${holds ? 'yes' : 'no'} | ` +
        `${f(c)} | ${ctx} | ${out} | ${rs.map((r) => r.turns ?? '-').join(' / ')} | ${failed.join(', ') || '-'} |`,
    );
  }
  lines.push(
    '',
    `Tasks holding (every run at threshold): ${holding} / ${measured}. Runs: ${records.length}. Total cost: $${f(cost)}.`,
    '',
  );
  return lines.join('\n');
}
