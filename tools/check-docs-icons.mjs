// BACKLOG mermaid node icons (3D-84, D-208): every WP node label is `<status icon> <type icon> 3D-NN <label>`, taken
// from the row's `Status` and `Type` cells, and a legend line follows the graph. Icon set: D-222; type values:
// D-221. `check-docs` reports a missing, stale or hand-edited icon or legend; `check-docs --fix` rewrites them.

/** @type {Record<string, string>} row status -> icon */
export const STATUS_ICON = {
  done: '✅',
  'in-progress': '🚧',
  review: '🔍',
  ready: '▶️',
  proposed: '💡',
  blocked: '⛔',
  superseded: '↪️',
  dropped: '🗑️',
};

/** @type {Record<string, string>} row type -> icon */
export const TYPE_ICON = {
  spec: '📐',
  kernel: '⚙️',
  service: '🖥️',
  tests: '🧪',
  tooling: '🔧',
  mirror: '🔗',
};

/** @type {Record<string, string>} type -> legend wording */
const TYPE_NAME = {
  spec: 'ADR/spec',
  kernel: 'kernel code',
  service: 'service code',
  tests: 'tests/fixtures',
  tooling: 'tooling',
  mirror: 'mirror in another repository',
};

export const TYPES = Object.keys(TYPE_ICON);
export const LEGEND_PREFIX = '**Legend:**';

/** The generated legend line. */
export function legendLine() {
  const st = Object.entries(STATUS_ICON).map(([s, i]) => `${i} ${s}`).join(' · ');
  const ty = TYPES.map((t) => `${TYPE_ICON[t]} ${TYPE_NAME[t]} (\`${t}\`)`).join(' · ');
  return `${LEGEND_PREFIX} status ${st}. Type ${ty}. Icons are generated by \`check-docs --fix\` from the row (D-208).`;
}

/** Mermaid node line: indent + `D<n>["`, the text before the first id, the id and the rest. */
const NODE = /^(\s*D[\d_]+\[")([^"]*?)(3D-(\d+(?:\.\d+)?)(?![\d.])[^"]*"\].*)$/;

/**
 * Compare node icons and the legend with the rows.
 * @param {string[]} lines BACKLOG lines
 * @param {{id: string, status: string, type: string}[]} rows
 * @returns {{problems: string[], fixed: string[]}} fixed: the lines with icons and legend regenerated
 */
export function icons(lines, rows) {
  /** @type {string[]} */
  const problems = [];
  const fixed = [...lines];
  const open = lines.findIndex((l) => l.trim() === '```mermaid');
  if (open < 0) return { problems, fixed };
  const byId = new Map(rows.map((r) => [r.id, r]));
  let close = open + 1;
  for (; close < lines.length && lines[close].trim() !== '```'; close++) {
    const m = NODE.exec(lines[close]);
    if (!m) continue;
    const row = byId.get(`3D-${m[4]}`);
    const si = row && STATUS_ICON[row.status];
    const ti = row && TYPE_ICON[row.type];
    if (!si || !ti) continue; // missing row, unknown status or type: reported by the row checks
    const want = `${si} ${ti} `;
    if (m[2] !== want) {
      problems.push(`docs/BACKLOG.md:${close + 1}: node 3D-${m[4]} icons "${m[2].trim()}" should be "${want.trim()}" (status ${row.status}, type ${row.type}); run check-docs --fix (D-208)`);
      fixed[close] = m[1] + want + m[3];
    }
  }
  if (close >= lines.length) return { problems, fixed };
  const legend = legendLine();
  const at = close + 2;
  if ((lines[at] ?? '').startsWith(LEGEND_PREFIX)) {
    if (lines[at] !== legend) {
      problems.push(`docs/BACKLOG.md:${at + 1}: icon legend differs from the generated one; run check-docs --fix (D-208)`);
      fixed[at] = legend;
    }
  } else {
    problems.push(`docs/BACKLOG.md:${close + 1}: icon legend missing under the graph; run check-docs --fix (D-208)`);
    fixed.splice(close + 1, 0, '', legend);
  }
  return { problems, fixed };
}
