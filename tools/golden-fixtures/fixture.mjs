// Fixture definition -> files (format: fixtures/README.md). Every file is UTF-8 JSON or Markdown with "\n" endings.

import { PROJECT_ID } from './brep.mjs';
import { SPEC, V03 } from './source.mjs';

/**
 * @typedef {{ what: string, mark: '[P]' | '[A]' | 'TBD', why: string }} Mark
 * @typedef {object} Step
 * @property {'IMPORT' | 'COMMAND' | 'EXPORT' | 'REQUEST' | 'WORLD_LOCAL_ROUNDTRIP'} step
 * @property {string} [note]
 * @typedef {object} Def
 * @property {string} gt
 * @property {Record<string, unknown>} inputs file name -> JSON content
 * @property {any[]} steps
 * @property {Record<string, unknown>} assert values from the v0.3 §12 row, or the spec §13 row of a case v0.3 does not
 *   have (3D-105); every number and CODE appears in it
 * @property {{ source: string, assert: Record<string, unknown> }[]} [decided] values from later decisions (D-NN)
 * @property {Mark[]} marks
 * @property {string} check the independent check (v0.2 F.3), one paragraph
 */

/**
 * Stable JSON: two-space indent, arrays of numbers / short strings on one line, trailing newline.
 * @param {unknown} v
 */
export const json = (v) => `${JSON.stringify(v, null, 2).replace(/\[\n\s+([^[\]{}"]*|(?:"[^"[\]]*",?\s*)*)\n\s*\]/g,
  (_, inner) => `[${inner.split(/,\n\s*/).join(', ')}]`)}\n`;

/**
 * A COMMIT command envelope (command.schema.json). [A] Phase COMMIT without `previewId`: a runner that needs PREVIEW
 * first (v0.3 §3) sends the same command as PREVIEW and copies the returned `previewId`.
 * @param {{ gt: string, n: number, buildingId: string, operation: string, payload: object, expectedVersion: number,
 *   actorId?: string, targetState?: 'DRAFT_SOLID' | 'VALID_SOLID' }} c
 */
export function command(c) {
  return {
    step: 'COMMAND',
    command: {
      schemaVersion: '1', commandId: `cmd-${c.gt.toLowerCase()}-${c.n}`, projectId: PROJECT_ID, buildingId: c.buildingId,
      actorId: c.actorId ?? 'usr-operator', operation: c.operation, phase: 'COMMIT', expectedVersion: c.expectedVersion,
      payload: c.payload, coordinateFrame: 'LOCAL', targetState: c.targetState ?? 'VALID_SOLID',
    },
  };
}

/**
 * @param {Def} def
 * @param {{ rows: Map<string, import('./source.mjs').V03Row>, preamble: string }} v03
 * @param {Map<string, { module: string, row: string, input: string, expected: string }>} spec13
 * @returns {Map<string, string>} relative path -> content
 */
export function render(def, v03, spec13) {
  const row = spec13.get(def.gt);
  if (!row) throw new Error(`${def.gt}: not in spec §13`);
  const own = { module: row.module, row: row.row };
  // v0.3 §12 is the source where it has the case; otherwise the owner-accepted spec §13 row (3D-105, D-332)
  const src = /** @type {import('./source.mjs').V03Row & { spec?: boolean }} */ (v03.rows.get(def.gt) ?? { id: def.gt, gate: '', input: row.input, expected: row.expected, spec: true });
  const dir = `fixtures/${def.gt}`;
  /** @type {Map<string, string>} */
  const out = new Map();
  for (const [name, content] of Object.entries(def.inputs)) out.set(`${dir}/${name}`, json(content));
  out.set(`${dir}/steps.json`, json(def.steps));
  out.set(`${dir}/expected.json`, json({
    gt: def.gt,
    source: src.spec ? { document: SPEC, section: '§13', input: src.input, expected: src.expected }
      : { document: V03, section: '§12', gate: src.gate, input: src.input, expected: src.expected },
    tolerance: { areaM2: 0.01, volumeM3: 0.01, source: 'v0.3 §12 preamble, unless the row states otherwise' },
    assert: def.assert,
    decided: def.decided ?? [],
    owner: own,
  }));
  out.set(`${dir}/README.md`, readme(def, src, own));
  return out;
}

/** @param {Def} def @param {import('./source.mjs').V03Row & { spec?: boolean }} src @param {{ module: string, row: string }} own */
function readme(def, src, own) {
  const files = [...Object.keys(def.inputs), 'steps.json', 'expected.json'].map((f) => `\`${f}\``).join(', ');
  const marks = def.marks.length
    ? ['| Item | Mark | Reason |', '|---|---|---|', ...def.marks.map((m) => `| ${m.what} | ${m.mark} | ${m.why} |`)].join('\n')
    : 'None: every input value comes from the v0.3 §12 row.';
  const from = src.spec ? 'spec §13' : 'v0.3 §12';
  return [
    `# ${def.gt}`,
    '',
    'Generated by `node tools/golden-fixtures/cli.mjs` (3D-07); do not edit by hand. Format: [fixtures/README.md](../README.md).',
    '',
    src.spec ? `- Module ${own.module}; row ${own.row} (spec §13).` : `- Gate ${src.gate}; module ${own.module}; row ${own.row} (spec §13).`,
    `- Input (${from}, verbatim): ${src.input}`,
    `- Expected (${from}, verbatim): ${src.expected}`,
    `- Files: ${files}.`,
    '- Frame: local, X east, Y north, Z up, metres; rings counter-clockwise seen from outside.',
    '',
    `## Choices not given by ${from}`,
    '',
    marks,
    '',
    '## Independent check (v0.2 F.3)',
    '',
    def.check,
    '',
  ].join('\n');
}
