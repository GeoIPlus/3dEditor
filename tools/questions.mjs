#!/usr/bin/env node
// One list of open owner questions (3D-138, D-475 part C). Generates docs/QUESTIONS.md from
//  - blocking questions: section "## Open questions" of the WP checkpoints `.agent/checkpoints/3D-*.md`;
//  - provisional decisions awaiting the owner: rows of docs/decisions/RISKS.md without a review row.
// Sources: the working tree, plus with `--remote` every `origin/wp/3d-*` branch not yet merged into HEAD (its
// checkpoint replaces the working-tree one; its RISKS.md rows join by risk id, the working tree wins).
// Usage: node tools/questions.mjs [--root dir] [--remote] [--write]   (without --write: print to stdout)
// The coordinator runs it with --remote --write (merge-wp); the output is deterministic for the same inputs.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RISKS, QUESTIONS, parseRisks, parseOpenQuestions } from './questions-parse.mjs';

/**
 * @typedef {{wp: string, source: string, checkpoints: Map<string, string>, risks: string}} Tree
 *   source: 'working tree' or the branch name; checkpoints: WP id -> text; risks: RISKS.md text ('' when absent)
 */

/** @param {string} root @returns {Tree} */
function workingTree(root) {
  const dir = join(root, '.agent/checkpoints');
  /** @type {Map<string, string>} */
  const checkpoints = new Map();
  if (existsSync(dir)) {
    for (const f of readdirSync(dir).sort()) {
      const m = /^(3D-[\d.]+)\.md$/.exec(f);
      if (m) checkpoints.set(m[1], readFileSync(join(dir, f), 'utf8'));
    }
  }
  const risks = existsSync(join(root, RISKS)) ? readFileSync(join(root, RISKS), 'utf8') : '';
  return { wp: '', source: 'working tree', checkpoints, risks };
}

/** @param {string} root @param {string[]} args @returns {string} */
const git = (root, args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });

/** @param {string} root @returns {Tree[]} unmerged WP branches on origin */
function remoteTrees(root) {
  const refs = git(root, ['for-each-ref', '--format=%(refname:short)', 'refs/remotes/origin/wp/']).split('\n').filter(Boolean).sort();
  /** @type {Tree[]} */
  const out = [];
  for (const ref of refs) {
    const m = /^origin\/wp\/3d-([\d.]+)-/.exec(ref);
    if (!m) continue;
    try { git(root, ['merge-base', '--is-ancestor', ref, 'HEAD']); continue; } catch { /* not merged */ }
    const show = (/** @type {string} */ p) => { try { return git(root, ['show', `${ref}:${p}`]); } catch { return ''; } };
    const wp = `3D-${m[1]}`;
    const cp = show(`.agent/checkpoints/${wp}.md`);
    out.push({ wp, source: ref.replace(/^origin\//, ''), checkpoints: new Map(cp ? [[wp, cp]] : []), risks: show(RISKS) });
  }
  return out;
}

/** @param {string} s */
const esc = (s) => s.replace(/\|/g, '\\|');

/**
 * Build docs/QUESTIONS.md from the trees (first tree = working tree).
 * @param {Tree[]} trees
 * @returns {{text: string, problems: string[]}}
 */
export function buildQuestions(trees) {
  /** @type {string[]} */
  const problems = [];
  /** @type {Map<string, {text: string, source: string}>} */
  const checkpoints = new Map();
  for (const t of trees) for (const [wp, text] of t.checkpoints) checkpoints.set(wp, { text, source: t.source });
  /** @type {string[]} */
  const blocking = [];
  for (const [wp, { text, source }] of [...checkpoints].sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true }))) {
    const r = parseOpenQuestions(text, `${source}:.agent/checkpoints/${wp}.md`);
    problems.push(...r.problems);
    for (const q of r.items) if (q.kind === 'blocking') blocking.push(`| ${wp} | ${esc(q.text)} | ${q.since} | ${source} |`);
  }
  /** @type {Map<string, {risk: import('./questions-parse.mjs').Risk, source: string}>} */
  const risks = new Map();
  const reviewed = new Set();
  for (const t of trees) {
    if (!t.risks) continue;
    const r = parseRisks(t.risks);
    if (t.source === 'working tree') problems.push(...r.problems);
    for (const risk of r.risks) if (!risks.has(risk.id)) risks.set(risk.id, { risk, source: t.source });
    for (const v of r.reviews) reviewed.add(v.risk);
  }
  const pending = [...risks.values()].filter((x) => !reviewed.has(x.risk.id))
    .sort((a, b) => a.risk.id.localeCompare(b.risk.id, 'en', { numeric: true }))
    .map(({ risk, source }) => `| ${risk.id} | ${risk.wp} | ${risk.decision} | ${esc(risk.chosen)} | ${risk.date} | ${source} |`);
  const none = (/** @type {number} */ cols) => `| none |${' |'.repeat(cols - 1)}`;
  const text = [
    '# Open questions to the owner',
    '',
    'Generated by `node tools/questions.mjs --remote --write` (3D-138, D-475); do not edit by hand. Sources: blocking',
    'questions from the section "Open questions" of the WP checkpoints, provisional decisions from',
    '[decisions/RISKS.md](decisions/RISKS.md) without a review row; unmerged `wp/` branches included. Rules: AGENTS.md',
    '§2 item 2 and §3, `.claude/skills/wp-session`.',
    '',
    '## Blocking (a session waits or has handed off)',
    '',
    '| WP | Question | Since | Source |',
    '|---|---|---|---|',
    ...(blocking.length ? blocking : [none(4)]),
    '',
    '## Provisional decisions awaiting confirmation',
    '',
    '| Risk | WP | Decision | Chosen | Since | Source |',
    '|---|---|---|---|---|---|',
    ...(pending.length ? pending : [none(6)]),
    '',
  ].join('\n');
  return { text, problems };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  const r = args.indexOf('--root');
  const root = r >= 0 ? resolve(args[r + 1]) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const trees = [workingTree(root), ...(args.includes('--remote') ? remoteTrees(root) : [])];
  const { text, problems } = buildQuestions(trees);
  for (const p of problems) console.error(p);
  if (args.includes('--write')) writeFileSync(join(root, QUESTIONS), text);
  else process.stdout.write(text);
  process.exit(problems.length ? 1 : 0);
}
